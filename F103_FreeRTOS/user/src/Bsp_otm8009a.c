static void Otm8009a_ShowChar(char chr, uint16_t x,uint16_t y,uint16_t font_color, uint16_t back_color, uint8_t size)
{  
    uint8_t temp;
    uint8_t pos,t;
	unsigned char display_char = chr-' ';

	Otm8009a_SetWindows(x,y,x+size/2-1,y+size-1);
	
	for(pos=0;pos<size;pos++)
	{
		if(size==12)
		{
			temp=asc2_1206[display_char][pos]; //the size is 12*06
		}
		else 
		{
			temp=asc2_1608[display_char][pos]; //the size is 16*08
		}

		for(t=0; t<size/2; t++)
		{                 
			if(temp & 0x01)
			{
				Otm8009a_Write_Data(font_color);
			}
			else 
			{
				Otm8009a_Write_Data(back_color);
			}
			temp >>= 1; 
		}
	}	
	//Otm8009a_SetWindows(0,0,lcddev.width-1,lcddev.height-1);   	 	  
}

void Otm8009a_ShowString(char* string, uint16_t x,uint16_t y,uint16_t font_color, uint16_t back_color, uint8_t size)
{
	uint8_t pos = 0;

	while (string[pos] != '\0')
    {
        Otm8009a_ShowChar(string[pos], x + (pos*(size/2)), y, font_color, back_color, size);
        pos++;
    }
}

void Otm8009a_ShowNum(uint32_t target_num, uint8_t num_size, uint16_t x,uint16_t y,uint16_t font_color, uint16_t back_color, uint8_t size)
{
	uint8_t i = 0;
	uint8_t pos = 0;
	uint32_t multi = 1;
	uint8_t multi_cnt = 0;
	unsigned char digit = 0;

	for (i = num_size; i > 0; i--)
	{
		for (multi_cnt = 0; multi_cnt < i -1; multi_cnt++)
		{
			multi = multi * 10;
		}
		digit = (target_num / multi) % 10;
		Otm8009a_ShowChar(digit + 48, x + (pos*(size/2)), y, font_color, back_color, size);
		pos++;
		multi = 1;
	}

}

