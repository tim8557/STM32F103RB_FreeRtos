#define OTM8009A_WR_CLR       OTM8009A_GPIO_TYPE->BRR=1<<OTM8009A_WR
#define OTM8009A_RS_CLR       OTM8009A_GPIO_TYPE->BRR=1<<OTM8009A_RS
